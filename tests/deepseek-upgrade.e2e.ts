  await page.getByLabel("本轮思考强度").selectOption("low");
  await page.getByLabel("本轮联网方式").selectOption("native");
  await page.getByLabel("联网任务", { exact: true }).selectOption("read");
  await page.getByLabel("对话指令").fill("阅读 https://api-docs.deepseek.com/zh-cn/guides/thinking_mode/ 并整理要点");
  await page.screenshot({ path: out + "/desktop.png", fullPage: true });
  await page.getByLabel("检索范围", { exact: true }).selectOption("local");
  await expect(page.getByLabel("本轮联网方式")).toHaveCount(0);
  await expect(page.getByLabel("联网任务", { exact: true })).toHaveCount(0);
  await page.getByLabel("检索范围", { exact: true }).selectOption("both");
  await page.setViewportSize({ width: 390, height: 844 });
