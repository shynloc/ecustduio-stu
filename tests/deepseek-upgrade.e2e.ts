  assert.deepEqual(errors, []);
  const result = { ok: true, widths: [1440, 390], themes: ["scholar"], errors, checks: ["settings persistence", "per-turn controls", "local-only hides web controls", "mobile no horizontal overflow"] };
  writeFileSync(out + "/result.json", JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
